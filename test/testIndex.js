import * as recognizer from '../lib/models/recognizer.js';
import {MAX_PAGE_SIDE, ORIENTATIONS, loadRecognizer, pageOrientation, pageText, recognize} from '../lib/index.js';
import {Buffer} from 'node:buffer';
import {strict as assert} from 'node:assert';
import {makeModule} from './helpers.js';
import {readFileSync} from 'node:fs';
import test from 'node:test';


// An RGBA page (paper 230) with dark boxes (ink 30) - each [x, y, width, height]
function rgbaPage(width, height, rects) {
    const data = new Uint8ClampedArray(width * height * 4).fill(230);
    for (const [left, top, rectWidth, rectHeight] of rects) {
        for (let row = top; row < top + rectHeight; row++) {
            data.fill(30, (row * width + left) * 4, (row * width + left + rectWidth) * 4);
        }
    }
    return {width, height, data};
}


// A line of "characters" - count boxes from x at a top, sloping down slope pixels per pixel
function characters(count, left, top, slope = 0) {
    return Array.from({'length': count}, (_value, ix) => [left + ix * 15, top + Math.round(ix * 15 * slope), 10, 20]);
}


test('loadRecognizer', () => {
    // The package's model, loaded once
    const model = loadRecognizer();
    assert.equal(loadRecognizer(), model);
    assert.equal(model.manifest, recognizer.manifest);

    // Another model module, loaded each time
    const module = makeModule([], {});
    assert.notEqual(loadRecognizer(module), loadRecognizer(module));
});


test('model module', () => {
    // The generated module, as the package expects it
    const {manifest} = recognizer;
    assert.equal(manifest.height, 32);
    assert.equal(manifest.margin, 48);
    assert.equal(manifest.stride, 4);
    assert.equal(manifest.alphabet[0], ' ');
    const out = manifest.tensors.find((entry) => entry.name === 'out.weight');
    assert.equal(out.shape[0], manifest.alphabet.length + 1);
    const text = readFileSync(new URL('../lib/models/recognizer.js', import.meta.url), 'utf-8');
    assert.match(text, /^\/\/ Generated by picoocr_train\.export/);
});


test('recognize', () => {
    // Two paragraphs of "characters" - the second line level, the page skewed slightly
    const image = rgbaPage(400, 260, [...characters(12, 30, 40, 0.02), ...characters(12, 30, 70, 0.02), ...characters(8, 30, 160, 0.02)]);
    const progress = [];
    const result = recognize(image, {'onProgress': (done, total) => progress.push([done, total])});
    assert.equal(result.scale, 1);
    assert.ok(Math.abs(result.angle - Math.atan(0.02)) < 0.003, `angle ${result.angle}`);
    assert.equal(result.lines.length, 3);
    assert.deepEqual(progress, [[1, 3], [2, 3], [3, 3]]);
    assert.deepEqual(result.lines.map((line) => line.paragraph), [true, false, true]);
    for (const line of result.lines) {
        assert.equal(typeof line.text, 'string');
        assert.ok(line.confidence > 0 && line.confidence <= 1);
        assert.deepEqual(Object.keys(line.box), ['x', 'y', 'width', 'height']);
    }
    assert.equal(result.text, pageText(result.lines));

    // A large blank page, scaled to MAX_PAGE_SIDE - level, no lines
    const blank = recognize(rgbaPage(MAX_PAGE_SIDE * 2, 100, []));
    assert.equal(blank.scale, 0.5);
    assert.equal(blank.angle, 0);
    assert.deepEqual(blank.lines, []);
    assert.equal(blank.text, '');

    // A given model
    const model = loadRecognizer();
    assert.equal(recognize(image, {model}).text, result.text);
});


test('pageText', () => {
    const lines = [
        {'text': 'One', 'paragraph': true},
        {'text': 'two', 'paragraph': false},
        {'text': '', 'paragraph': true},
        {'text': 'Three', 'paragraph': true}
    ];
    assert.equal(pageText(lines), 'One\ntwo\n\nThree');
    assert.equal(pageText([]), '');
});


// The text line fixture (test/fixtures/line.json) as an RGBA image, flipped
const fixture = JSON.parse(readFileSync(new URL('fixtures/line.json', import.meta.url), 'utf-8'));
function fixtureImage(horizontal, vertical) {
    const {width, height} = fixture;
    const gray = Buffer.from(fixture.gray, 'base64');
    const data = new Uint8ClampedArray(width * height * 4);
    for (let row = 0; row < height; row++) {
        for (let column = 0; column < width; column++) {
            const value = gray[(vertical ? height - 1 - row : row) * width + (horizontal ? width - 1 - column : column)];
            data.fill(value, (row * width + column) * 4, (row * width + column) * 4 + 3);
            data[(row * width + column) * 4 + 3] = 255;
        }
    }
    return {width, height, data};
}


test('recognize, orientation', () => {
    // Each orientation - detected, and the line read upright
    for (const [index, name] of ORIENTATIONS.entries()) {
        const result = recognize(fixtureImage((index & 1) !== 0, (index & 2) !== 0));
        assert.equal(result.orientation, name);
        assert.match(result.text, /brown fox/);
    }

    // Not detected
    assert.equal(recognize(fixtureImage(true, false), {'orient': false}).orientation, 'upright');

    // No lines - upright
    assert.equal(pageOrientation(loadRecognizer(), {'width': 10, 'height': 10, 'data': new Float32Array(100)}, []), 0);
});

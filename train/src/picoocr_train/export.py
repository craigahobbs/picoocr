"""
The export - a training checkpoint as the package's model module (lib/models/recognizer.js), which lib/model.js loads
with a plain import (no fetch, no file system):

    python -m picoocr_train.export build/train/run/last.pt -o build/train/recognizer.js --parity build/train/parity.json

- Each batch norm is folded into its convolution (model.py export_layers), and the network listed as the manifest's
  layers.
- The convolutions' weights are quantized (quant.py) as the recipe's export section says - its bits, by GPTQ given each
  layer's input covariance over calibration lines (rendered apart from the validation sets - its own seed), or by
  nearest rounding; the biases stay float32. --float exports the float32 weights instead (the reference - make
  train-float, and tools/pagecheck.js --reference).
- The quantized network is validated against the float network (the validation sets' character error rates - run as
  the package runs the manifest, model.py run_layers) - the export fails if quantization costs more than
  MAX_QUANTIZATION_COST.
- The module exports manifest (the alphabet, the line input's height, margin, and stride, the layers, and the tensors'
  offsets in the weights) and weights (base64 of the bytes - packed weights, float32 scales and biases, each 4-byte
  aligned). Deflate barely shrinks quantized weights, and base64's third mostly disappears under the HTTP compression
  static hosts apply - so the bytes are stored as they are (the export prints the sizes).
- The parity data (--parity) - line inputs and their quantized class scores, and a page's line inputs - is what
  tools/parity.js checks the package against.
"""

import argparse
import base64
import gzip
import hashlib
import json
import sys
import zlib

import numpy
import torch

from . import RECIPE_PATH, log, read_json
from .data import render_samples, sorted_batches
from .image import LINE_HEIGHT, LINE_MARGIN, LINE_STRIDE, line_input
from .model import Recognizer, character_error_rate, greedy_decode, run_layers
from .quant import dequantize, layer_hessians, pack, quantize
from .train import load_paragraphs, split_fonts, validation_sets


# The largest validation character error rate quantization may add
MAX_QUANTIZATION_COST = 0.002

# The base64 lines' length
LINE_LENGTH = 120

# The generated module's header
HEADER = '// Generated by picoocr_train.export - do not edit'


# The model's export - (manifest, weights bytes, the tensors {name: (weight, bias)} as the package loads them). bits - the
# weights' width (None - float32: the reference); hessians - {name: input covariance} for GPTQ (None - nearest rounding).
def export_model(model, recipe, provenance, bits=None, hessians=None):
    layers, folded = model.export_layers()
    blob = bytearray()
    entries = []
    tensors = {}

    # Append bytes at a 4-byte boundary - their offset
    def append(data):
        blob.extend(b'\0' * (-len(blob) % 4))
        offset = len(blob)
        blob.extend(data)
        return offset

    for name, (weight, bias) in folded.items():
        if bits is not None:
            integers, scales = quantize(weight, bits, None if hessians is None else hessians[name])
            offset = append(pack(integers, bits))
            scale_offset = append(scales.astype('<f4').tobytes())
            entries.append({
                'name': f'{name}.weight', 'shape': list(weight.shape), 'dtype': 'packed', 'bits': bits, 'offset': offset,
                'scaleOffset': scale_offset
            })
            weight = dequantize(integers, scales, weight.shape)
        else:
            weight = weight.float()
            offset = append(weight.numpy().astype('<f4').tobytes())
            entries.append({'name': f'{name}.weight', 'shape': list(weight.shape), 'dtype': 'float32', 'offset': offset})
        bias = bias.float()
        bias_offset = append(bias.numpy().astype('<f4').tobytes())
        entries.append({'name': f'{name}.bias', 'shape': list(bias.shape), 'dtype': 'float32', 'offset': bias_offset})
        tensors[name] = (weight, bias)
    manifest = {
        'version': 1,
        'alphabet': list(recipe['alphabet']),
        'height': LINE_HEIGHT,
        'margin': LINE_MARGIN,
        'stride': LINE_STRIDE,
        'parameters': sum(param.numel() for param in model.parameters()),
        'provenance': provenance,
        'layers': layers,
        'tensors': entries
    }
    return manifest, bytes(blob), tensors


# The model module's text
def module_text(manifest, weights):
    encoded = base64.b64encode(weights).decode('ascii')
    lines = '\n'.join(encoded[ix:ix + LINE_LENGTH] for ix in range(0, len(encoded), LINE_LENGTH))
    return '\n'.join([
        HEADER,
        f'// The PicoOCR line recognizer for lib/model.js loadModel - {manifest["parameters"]} parameters, '
        f'{f"{manifest["tensors"][0]["bits"]}-bit" if manifest["tensors"][0]["dtype"] == "packed" else "float32"} weights',
        f'// ({len(weights)} bytes, as base64), trained by picoocr_train.train.',
        '',
        f'export const manifest = {json.dumps(manifest, indent=4, ensure_ascii=False)};',
        '',
        'export const weights = `',
        lines,
        '`;',
        ''
    ])


# The character error rates of a network on batches - float (the model) and quantized (the exported tensors)
def quantized_errors(model, layers, tensors, batches, alphabet):
    texts = {'float': [], 'quantized': []}
    references = []
    with torch.no_grad():
        for inputs, steps, _, _, batch_texts in batches:
            texts['float'].extend(greedy_decode(model(inputs), steps.tolist(), alphabet))
            texts['quantized'].extend(greedy_decode(run_layers(layers, tensors, inputs), steps.tolist(), alphabet))
            references.extend(batch_texts)
    return {name: character_error_rate(decoded, references) for name, decoded in texts.items()}


# The parity data - line inputs (two of the shortest batch's, two of the longest's) and their class scores and texts,
# and a page's line inputs
def parity_data(layers, tensors, batches, alphabet, seed=1):
    lines = []
    for inputs, steps, _, _, _ in batches[:1] + batches[1:][-1:]:
        for index in range(min(2, len(inputs))):
            line = inputs[index:index + 1, :, :, :int(steps[index]) * LINE_STRIDE]
            with torch.no_grad():
                scores = run_layers(layers, tensors, line)
            lines.append({
                'width': line.shape[3],
                'data': line.reshape(-1).tolist(),
                'scores': scores[0].reshape(-1).tolist(),
                'text': greedy_decode(scores, [scores.shape[2]], alphabet)[0]
            })
    rng = numpy.random.default_rng(seed)
    page = (rng.random((90, 160)) * 255).astype(numpy.float32)
    page[30:50, 20:140] *= 0.3
    boxes = [[20, 30, 120, 20], [0, 0, 40, 12], [150, 80, 30, 25], [5, 40, 7, 3]]
    return {
        'lines': lines,
        'page': {'width': 160, 'height': 90, 'data': page.reshape(-1).tolist()},
        'boxes': [{'box': box, 'line': line_input(page, box).reshape(-1).tolist()} for box in boxes]
    }


def main(argv=None):
    parser = argparse.ArgumentParser(prog='python -m picoocr_train.export', description=__doc__.strip().split('\n\n', maxsplit=1)[0])
    parser.add_argument('checkpoint', help='the training checkpoint (train.py best.pt)')
    parser.add_argument('-o', '--output', required=True, help='the model module to write')
    parser.add_argument('--parity', help='the parity data to write (tools/parity.js)')
    parser.add_argument('--float', action='store_true', help='float32 weights - the quantized model\'s reference')
    parser.add_argument('--recipe', default=RECIPE_PATH, help='the recipe - its export section (train/data/train.json by default)')
    args = parser.parse_args(argv)

    # The checkpoint's model
    with open(args.checkpoint, 'rb') as file:
        checkpoint_sha256 = hashlib.sha256(file.read()).hexdigest()
    checkpoint = torch.load(args.checkpoint, weights_only=False)
    recipe = checkpoint['recipe']
    model = Recognizer(len(recipe['alphabet']) + 1, recipe['model'])
    model.load_state_dict(checkpoint['model'])
    model.eval()
    provenance = {'checkpoint': checkpoint_sha256[:16], 'step': checkpoint['step'], 'validation': checkpoint['validation']}
    # The weights - float, or quantized (GPTQ given the calibration lines' layer covariances)
    settings = read_json(args.recipe)['export']
    paragraphs = load_paragraphs(recipe['alphabet'])
    hessians = None
    if not args.float and settings['gptq']:
        calibration = render_samples(recipe, split_fonts('train'), paragraphs, settings['calibrationSeed'], settings['calibrationSamples'])
        layers, folded = model.export_layers()
        hessians = layer_hessians(layers, folded, sorted_batches(calibration, recipe['alphabet'], recipe['train']['batch']))
    bits = None if args.float else settings['bits']
    manifest, weights, tensors = export_model(model, recipe, provenance, bits=bits, hessians=hessians)

    # The quantized network's validation, against the float network
    validation = validation_sets(recipe, paragraphs)
    failed = False
    for name, batches in validation.items():
        errors = quantized_errors(model, manifest['layers'], tensors, batches, recipe['alphabet'])
        log(f'{name}: float {errors["float"]:.4f}, quantized {errors["quantized"]:.4f}')
        failed = failed or errors['quantized'] - errors['float'] > MAX_QUANTIZATION_COST

    # The module, and the parity data
    text = module_text(manifest, weights)
    with open(args.output, 'w', encoding='utf-8') as file:
        file.write(text)
    sizes = {
        'weights': len(weights), 'weightsDeflated': len(zlib.compress(weights, 9)),
        'module': len(text.encode('utf-8')), 'moduleGzip': len(gzip.compress(text.encode('utf-8'), 9))
    }
    log(f'wrote {args.output} {json.dumps(sizes)}')
    if args.parity:
        with open(args.parity, 'w', encoding='utf-8') as file:
            json.dump(parity_data(manifest['layers'], tensors, validation['unseen'], recipe['alphabet']), file)
        log(f'wrote {args.parity}')
    if failed:
        log(f'quantization costs more than {MAX_QUANTIZATION_COST} character error rate')
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())

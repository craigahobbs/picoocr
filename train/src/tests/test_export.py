"""
The tests of picoocr_train.export
"""

import base64
import io
import json
import os
import re
import tempfile
import unittest
import unittest.mock

import numpy
import torch

from picoocr_train import export
from picoocr_train.data import render_samples, sorted_batches
from picoocr_train.export import export_model, module_text, parity_data, quantized_errors

from .helpers import PARAGRAPHS, run_module, test_fonts, tiny_recipe
from .test_model import trained_recognizer


# The tests' validation sets
def validation(recipe):
    batches = sorted_batches(render_samples(recipe, test_fonts(), PARAGRAPHS, 3, 4), recipe['alphabet'], 2)
    return {'seen': batches, 'unseen': batches}


class TestExport(unittest.TestCase):

    def test_export_model(self):
        model = trained_recognizer()
        manifest, weights, tensors = export_model(model, tiny_recipe(), {'step': 1}, bits=5)
        self.assertEqual(manifest['height'], 32)
        self.assertEqual(manifest['margin'], 48)
        self.assertEqual(manifest['alphabet'], list(tiny_recipe()['alphabet']))
        self.assertEqual(manifest['parameters'], sum(param.numel() for param in model.parameters()))
        self.assertEqual(manifest['provenance'], {'step': 1})

        # Each tensor at a 4-byte boundary, as the package reads it
        for entry in manifest['tensors']:
            self.assertEqual(entry['offset'] % 4, 0)
            size = int(numpy.prod(entry['shape']))
            if entry['dtype'] == 'packed':
                self.assertEqual(entry['bits'], 5)
                packed = numpy.frombuffer(weights, dtype=numpy.uint8, count=(size * 5 + 7) // 8, offset=entry['offset'])
                bits = numpy.unpackbits(packed, bitorder='little')[:size * 5].reshape(size, 5)
                values = (bits * (1 << numpy.arange(5))).sum(axis=1) - 15
                scales = numpy.frombuffer(weights, dtype='<f4', count=entry['shape'][0], offset=entry['scaleOffset'])
                dequantized = values.reshape(entry['shape'][0], -1) * scales[:, None]
                name = entry['name'][:-len('.weight')]
                self.assertTrue(numpy.allclose(dequantized, tensors[name][0].reshape(entry['shape'][0], -1).numpy()))

        # The quantized network is close to the model
        inputs = torch.rand(1, 1, 32, 40)
        with torch.no_grad():
            self.assertTrue(torch.allclose(export.run_layers(manifest['layers'], tensors, inputs), model(inputs), atol=0.05))

        # GPTQ - given the layers' input covariances
        layers, folded = model.export_layers()
        hessians = {name: numpy.eye(weight[0].numel()) for name, (weight, _) in folded.items()}
        manifest, _, gptq_tensors = export_model(model, tiny_recipe(), {}, bits=5, hessians=hessians)
        self.assertTrue(all(torch.equal(gptq_tensors[name][0], weight) for name, (weight, _) in tensors.items()))
        self.assertEqual(len(layers), len(manifest['layers']))

        # Float - the model's own weights (as float32), and its scores
        manifest, weights, tensors = export_model(model, tiny_recipe(), {})
        self.assertTrue(all(entry['dtype'] == 'float32' for entry in manifest['tensors']))
        self.assertEqual(len(weights), 4 * sum(int(numpy.prod(entry['shape'])) for entry in manifest['tensors']))
        with torch.no_grad():
            self.assertTrue(torch.allclose(export.run_layers(manifest['layers'], tensors, inputs), model(inputs), atol=1e-5))

    def test_module_text(self):
        text = module_text({'parameters': 5, 'a': 'é', 'tensors': [{'dtype': 'packed', 'bits': 5}]}, bytes(range(200)))
        self.assertIn('5 parameters, 5-bit weights', text)
        self.assertIn('5 parameters, float32 weights', module_text({'parameters': 5, 'tensors': [{'dtype': 'float32'}]}, b''))
        self.assertTrue(text.startswith('// Generated by picoocr_train.export - do not edit\n'))
        self.assertIn('"a": "é"', text)
        encoded = re.search(r'export const weights = `\n([^`]*)`;', text).group(1)
        self.assertTrue(all(len(line) <= export.LINE_LENGTH for line in encoded.split('\n')))
        self.assertEqual(base64.b64decode(encoded.replace('\n', '')), bytes(range(200)))

    def test_quantized_errors_and_parity(self):
        recipe = tiny_recipe()
        model = trained_recognizer()
        manifest, _, tensors = export_model(model, recipe, {}, bits=5)
        sets = validation(recipe)
        errors = quantized_errors(model, manifest['layers'], tensors, sets['unseen'], recipe['alphabet'])
        self.assertEqual(sorted(errors), ['float', 'quantized'])
        parity = parity_data(manifest['layers'], tensors, sets['unseen'], recipe['alphabet'])
        self.assertEqual(len(parity['lines']), 4)
        self.assertLessEqual(parity['lines'][0]['width'], parity['lines'][3]['width'])

        # One batch
        self.assertEqual(len(parity_data(manifest['layers'], tensors, sets['unseen'][:1], recipe['alphabet'])['lines']), 2)
        line = parity['lines'][0]
        self.assertEqual(len(line['data']), 32 * line['width'])
        self.assertEqual(len(line['scores']), (len(recipe['alphabet']) + 1) * line['width'] // 4)
        self.assertEqual(len(parity['page']['data']), 160 * 90)
        self.assertEqual([len(box['line']) % 32 for box in parity['boxes']], [0, 0, 0, 0])

    def test_main(self):
        recipe = tiny_recipe()
        model = trained_recognizer()
        with tempfile.TemporaryDirectory() as temp_dir, \
             unittest.mock.patch.object(export, 'validation_sets', return_value=validation(recipe)), \
             unittest.mock.patch.object(export, 'load_paragraphs', return_value=PARAGRAPHS), \
             unittest.mock.patch.object(export, 'split_fonts', return_value=test_fonts()), \
             unittest.mock.patch('sys.stderr', io.StringIO()) as stderr:
            checkpoint = os.path.join(temp_dir, 'best.pt')
            torch.save({'model': model.state_dict(), 'recipe': recipe, 'step': 3, 'validation': {'seen': 0.5}}, checkpoint)
            recipe_path = os.path.join(temp_dir, 'recipe.json')
            with open(recipe_path, 'w', encoding='utf-8') as file:
                json.dump(recipe, file)
            output = os.path.join(temp_dir, 'recognizer.js')
            parity = os.path.join(temp_dir, 'parity.json')

            # Nearest rounding
            with open(os.path.join(temp_dir, 'nearest.json'), 'w', encoding='utf-8') as file:
                json.dump({**recipe, 'export': {**recipe['export'], 'gptq': False}}, file)
            self.assertEqual(export.main([checkpoint, '-o', output, '--recipe', os.path.join(temp_dir, 'nearest.json')]), 0)

            # GPTQ, with the parity data
            self.assertEqual(export.main([checkpoint, '-o', output, '--parity', parity, '--recipe', recipe_path]), 0)
            with open(output, encoding='utf-8') as file:
                manifest = json.loads(re.search(r'export const manifest = (\{.*?\n\});', file.read(), re.DOTALL).group(1))
            self.assertEqual(manifest['tensors'][0]['bits'], 5)
            self.assertEqual(manifest['provenance']['step'], 3)
            self.assertEqual(len(manifest['provenance']['checkpoint']), 16)
            with open(parity, encoding='utf-8') as file:
                self.assertEqual(len(json.load(file)['lines']), 4)
            self.assertIn('"weightsDeflated"', stderr.getvalue())

            # Float weights
            self.assertEqual(export.main([checkpoint, '-o', output, '--float', '--recipe', recipe_path]), 0)
            with open(output, encoding='utf-8') as file:
                self.assertIn('float32 weights', file.read())

            # Quantization costs too much - no parity data
            with unittest.mock.patch.object(export, 'MAX_QUANTIZATION_COST', -1):
                self.assertEqual(export.main([checkpoint, '-o', output, '--recipe', recipe_path]), 1)
            self.assertIn('quantization costs more than -1', stderr.getvalue())

    def test_main_module(self):
        code, stdout, _ = run_module('picoocr_train.export', ['--help'])
        self.assertEqual(code, 0)
        self.assertIn('usage: python -m picoocr_train.export', stdout)
